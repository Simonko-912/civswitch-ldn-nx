#!/usr/bin/env python3
"""Generate the embedded v0.8 persistent-installer JavaScript header.

The installer logic and save template originate from Gezine/CivSwitch.  This
script wraps and compresses the bundled Remote JS Loader exactly like upstream
install.py, then emits a C header consumed by the Switch homebrew application.
"""

import io
import json
import os
import subprocess
import tempfile

from install import BLOCK, STAGER


HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CORE = os.path.join(HERE, "core.js")
TEMPLATE = os.path.join(ROOT, "data", "save_template.bin")
OUTPUT = os.path.join(ROOT, "source", "installer_payload.h")


def c_string_lines(value, width=96):
    return "\n".join("    " + json.dumps(value[i:i + width])
                     for i in range(0, len(value), width))


def main():
    core = io.open(CORE, encoding="utf-8").read().replace("\r\n", "\n")
    wrapped = ("(async function() {\ntry{\n" + core +
               "\n} catch (e) {\nawait log('EXCEPTION: ' + e.message);\n"
               "await log(e.stack);\n}\n})();")

    with tempfile.TemporaryDirectory(prefix="civswitch-v08-") as temp:
        wrapped_path = os.path.join(temp, "wrapped.js")
        hex_path = os.path.join(temp, "stage.hex")
        io.open(wrapped_path, "w", encoding="utf-8", newline="\n").write(wrapped)
        subprocess.run([
            "node", os.path.join(HERE, "compress_stage.js"),
            wrapped_path, hex_path,
        ], check=True)
        stage_hex = io.open(hex_path, encoding="ascii").read().strip()

    template = open(TEMPLATE, "rb").read()
    if len(template) < 4096 or template[:4] != b"CIV7":
        raise SystemExit("bad save_template.bin")
    template_b64_len = ((len(template) + 2) // 3) * 4
    apply_js = (BLOCK
                .replace("__STAGER__", json.dumps(STAGER))
                .replace("__STAGE_HEX__", json.dumps(stage_hex))
                .replace("__TPL_B64_LEN__", str(template_b64_len)))

    header = """// Generated by installer/generate_assets.py from Gezine/CivSwitch assets.
// Do not edit directly.
#ifndef CIVSWITCH_INSTALLER_PAYLOAD_H
#define CIVSWITCH_INSTALLER_PAYLOAD_H

static const char installer_apply_js[] =
%s;

static const unsigned installer_template_base64_length = %uU;

#endif
""" % (c_string_lines(apply_js), template_b64_len)
    io.open(OUTPUT, "w", encoding="ascii", newline="\n").write(header)
    print("generated %s (%d bytes JS, %d base64 bytes)" %
          (OUTPUT, len(apply_js), template_b64_len))


if __name__ == "__main__":
    main()
